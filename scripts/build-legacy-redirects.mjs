#!/usr/bin/env node
// Generates provisioning/nginx/legacy-redirects.map from legacy-redirects.csv.
// Edit the CSV, then run: node scripts/build-legacy-redirects.mjs
// With --check, fails if the committed map is out of date (used by CI).
import { readFileSync, writeFileSync } from "node:fs";

const CSV = "provisioning/nginx/legacy-redirects.csv";
const MAP = "provisioning/nginx/legacy-redirects.map";
const BASE = "/freeswitch/";

export function readRows(path = CSV) {
  return readFileSync(path, "utf8")
    .trim()
    .split("\n")
    .slice(1)
    .map((line) => {
      const [kind, legacy, target] = line.replace(/\r$/, "").split(",");
      return { kind, legacy, target };
    });
}

export function buildMap(rows) {
  const out = [
    "# GENERATED by scripts/build-legacy-redirects.mjs from legacy-redirects.csv. Do not edit.",
    "# Matched against $uri, so query strings on old links do not defeat these rules.",
    "# Exact pages win over the section rules, and unknown legacy URLs fall through",
    "# to the home page rules in redirects.map.",
    "",
  ];
  const q = (s) => `"${s}"`;
  for (const { kind, legacy, target } of rows) {
    if (kind === "section") continue;
    out.push(`${q(BASE + legacy)} ${q(BASE + target)};`);
    out.push(`${q(BASE + legacy + "/")} ${q(BASE + target)};`);
  }
  out.push("");
  const sections = rows
    .filter((r) => r.kind === "section")
    .sort((a, b) => b.legacy.length - a.legacy.length);
  for (const { legacy, target } of sections) {
    out.push(`${q(`~*^${BASE}${legacy}(/|$)`)} ${q(BASE + target)};`);
  }
  return out.join("\n") + "\n";
}

if (process.argv[1].endsWith("build-legacy-redirects.mjs")) {
  const generated = buildMap(readRows());
  if (process.argv.includes("--check")) {
    if (readFileSync(MAP, "utf8") !== generated) {
      console.error(`${MAP} is out of date. Run: node scripts/build-legacy-redirects.mjs`);
      process.exit(1);
    }
    console.log(`${MAP} is up to date.`);
  } else {
    writeFileSync(MAP, generated);
    console.log(`Wrote ${MAP}`);
  }
}
